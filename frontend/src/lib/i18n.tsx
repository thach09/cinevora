const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, vi };
const storageKey = "cinevora.locale";

function initialLocale(): Locale {
  try {
    const saved = window.localStorage.getItem(storageKey);
    if (saved === "en" || saved === "vi") return saved;
  } catch { /* Storage can be unavailable in private contexts. */ }
  return navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en";
}

function interpolate(template: string, values?: TranslationValues) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values?.[key] ?? `{${key}}`));
}

type I18nValue = { locale: Locale; setLocale: (locale: Locale) => void; t: Translator; categoryName: (name: string) => string };
const I18nContext = createContext<I18nValue | null>(null);

const seededCategories: Record<string, Record<Locale, string>> = {
  "Hành Động": { en: "Action", vi: "Hành động" },
  "Tình Cảm": { en: "Romance", vi: "Tình cảm" },
  "Kinh Dị": { en: "Horror", vi: "Kinh dị" },
  "Hài Hước": { en: "Comedy", vi: "Hài hước" },
  "Khoa Học Viễn Tưởng": { en: "Science fiction", vi: "Khoa học viễn tưởng" },
  "Hoạt hình": { en: "Animation", vi: "Hoạt hình" },
  "Tài liệu": { en: "Documentary", vi: "Tài liệu" },
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);
  useEffect(() => {
    document.documentElement.lang = locale;
    try { window.localStorage.setItem(storageKey, locale); } catch { /* Preference remains in memory. */ }
  }, [locale]);
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => interpolate(dictionaries[locale][key], values),
    categoryName: (name) => seededCategories[name]?.[locale] ?? name,
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}

export const intlLocale = (locale: Locale) => locale === "vi" ? "vi-VN" : "en-US";
